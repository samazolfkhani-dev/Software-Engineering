@bot.on_message()
async def handle_message(message):

    if not message.text:
        return

    text = message.text.strip().lower()

    if any(word in text for word in ["صبح بخیر", "صبحت بخیر", "صبح به خیر"]):
        category = "morning"

    elif any(word in text for word in ["شب بخیر", "شبت بخیر", "شب به خیر"]):
        category = "night"

    elif any(word in text for word in ["خداحافظ", "فعلا", "بای", "بدرود"]):
        category = "goodbye"

    elif any(word in text for word in ["اسمت", "اسم تو", "کی هستی", "چه کسی هستی"]):
        category = "identity"

    elif any(word in text for word in ["سلام", "درود"]):
        category = "greeting"

    elif any(word in text for word in ["خوبی", "چطوری", "حالت چطوره"]):
        category = "how_are_you"

    elif any(word in text for word in ["دلتنگ", "دلم تنگ", "دلم برات"]):
        category = "missing"

    elif any(word in text for word in ["عاشق", "دوستت دارم", "عشق"]):
        category = "love"

    elif any(word in text for word in ["تنها", "تنهایی", "بی کسم"]):
        category = "loneliness"

    elif any(word in text for word in ["خسته", "فرسوده", "از پا افتادم"]):
        category = "tired"

    elif any(word in text for word in ["ناامید", "امید", "امیدوار"]):
        category = "hope"

    elif any(word in text for word in ["غمگین", "ناراحتم", "غم دارم", "گریه"]):
        category = "sad"

    elif any(word in text for word in ["خوشحال", "شاد", "خوشحالم"]):
        category = "happy"

    elif any(word in text for word in ["ممنون", "مرسی", "سپاس", "متشکرم"]):
        category = "thanks"

    elif any(word in text for word in ["رفیق", "دوست", "رفاقت"]):
        category = "friendship"

    elif any(word in text for word in ["زندگی", "عمر", "زمان"]):
        category = "life"

    elif any(word in text for word in ["رویا", "آرزو", "آینده", "هدف"]):
        category = "dream"

    elif any(word in text for word in ["موفقیت", "موفق", "تلاش", "پیشرفت"]):
        category = "success"

    elif any(word in text for word in ["طبیعت", "بهار", "گل", "باران"]):
        category = "nature"

    elif any(word in text for word in ["ببخش", "معذرت", "عذرخواهی"]):
        category = "apology"

    else:
        category = "unknown"

    response = random.choice(responses[category])

    await message.reply(response)

